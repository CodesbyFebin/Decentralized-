// Protocol identifies the suite.
const Protocol = "dh/v1"

// SuiteVersion changes whenever vectors are added or change meaning.
const SuiteVersion = 1

// Suite is the vector file.
type Suite struct {
	Protocol string   `json:"protocol"`
	Version  int      `json:"version"`
	Note     string   `json:"note"`
	Vectors  []Vector `json:"vectors"`
}

// Vector is one test case. Expect is {"output": …} or {"error": "<code>"}.
type Vector struct {
	ID          string          `json:"id"`
	Op          string          `json:"op"`
	Description string          `json:"description"`
	Input       json.RawMessage `json:"input"`
	Expect      json.RawMessage `json:"expect"`
}

// Seed returns the hex seed of conformance identity n:
// BLAKE3("decentralized.host/conformance-seed/v1" || n)[:32].
func Seed(n byte) string {
	sum := blake3.Sum256(append([]byte("decentralized.host/conformance-seed/v1"), n))
	return hex.EncodeToString(sum[:32])
}

func ident(n byte) *identity.Identity {
	b, _ := hex.DecodeString(Seed(n))
	return identity.FromSeed(b)
}

// GenData materializes a "data_gen" input: xorshift64* seeded with seed,
// each step emitting 8 little-endian bytes, truncated to length; alg "zero"
// is length zero bytes; alg "pattern" repeats the bytes 0..250.
func GenData(alg string, seed uint64, length int) ([]byte, error) {
	out := make([]byte, length)
	switch alg {
	case "zero":
	case "pattern":
		for i := range out {
			out[i] = byte(i % 251)
		}
	case "xorshift64*":
		x := seed
		if x == 0 {
			return nil, errors.New("xorshift64* seed must be non-zero")
		}
		var w [8]byte
		for i := 0; i < length; i += 8 {
			x ^= x >> 12
			x ^= x << 25
			x ^= x >> 27
			binary.LittleEndian.PutUint64(w[:], x*0x2545F4914F6CDD1D)
			copy(out[i:], w[:])
		}
	default:
		return nil, fmt.Errorf("unknown data_gen alg %q", alg)
	}
	return out, nil
}

// Materialize expands generator shorthands in an input before it is sent
// to an adapter: {"data_gen":{"alg","seed","length"}} becomes {"data_b64"}.
func Materialize(op string, in json.RawMessage) (json.RawMessage, error) {
	if op != "chunk" {
		return in, nil
	}
	var r struct {
		Gen *struct {
			Alg    string `json:"alg"`
			Seed   uint64 `json:"seed"`
			Length int    `json:"length"`
		} `json:"data_gen"`
	}
	if err := json.Unmarshal(in, &r); err != nil || r.Gen == nil {
		return in, err
	}
	data, err := GenData(r.Gen.Alg, r.Gen.Seed, r.Gen.Length)
	if err != nil {
		return nil, err
	}
	return json.Marshal(map[string]any{"data_b64": data})
}

type gen struct {
	s   Suite
	err error
}

func (g *gen) add(op, id, desc string, input any) {
	if g.err != nil {
		return
	}
	raw, err := canon.Wire(input)
	if err != nil {
		g.err = fmt.Errorf("%s: %w", id, err)
		return
	}
	sent, err := Materialize(op, raw)
	if err != nil {
		g.err = fmt.Errorf("%s: %w", id, err)
		return
	}
	out, herr := Handle(op, sent)
	var expect any
	if herr != nil {
		var e *Error
		if !errors.As(herr, &e) || e.Code == CodeBadInput {
			g.err = fmt.Errorf("%s: reference adapter: %v", id, herr)
			return
		}
		expect = map[string]any{"error": e.Code}
	} else {
		expect = map[string]any{"output": out}
	}
	eb, err := canon.Marshal(expect)
	if err != nil {
		g.err = fmt.Errorf("%s: %w", id, err)
		return
	}
	g.s.Vectors = append(g.s.Vectors, Vector{ID: op + "/" + id, Op: op, Description: desc, Input: raw, Expect: eb})
}

// Generate builds the full, deterministic vector suite with the Go
// reference implementation.
func Generate() (*Suite, error) {
	g := &gen{s: Suite{Protocol: Protocol, Version: SuiteVersion,
		Note: "Generated by dh-conformance gen from the Go reference implementation. Do not edit by hand; see docs/protocol/conformance.md."}}
	genCanon(g)
	genIdentity(g)
	genHashes(g)
	genEnvelopes(g)
	genAudit(g)
	genCapabilities(g)
	genStorage(g)
	if g.err != nil {
		return nil, g.err
	}
	return &g.s, nil
}

